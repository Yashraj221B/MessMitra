export const getTranslation = (language: Language, key: keyof typeof translations.english): string => {
  return translations[language][key] || translations.english[key];
};

export const getDefaultLanguage = (role: 'manager' | 'member'): Language => {
  return role === 'manager' ? 'marathi' : 'english';
};

// Helper to check if text has bilingual format
export const hasBilingualFormat = (text: string): boolean => {
  return text.includes('(') && text.includes(')');
};
